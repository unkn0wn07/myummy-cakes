// Helper: get related products (same category, excluding current)
export function getRelated(slug, limit = 3) {
  const current = PRODUCTS.find((p) => p.slug === slug);
  if (!current) return PRODUCTS.slice(0, limit);
  return PRODUCTS.filter((p) => p.slug !== slug && p.category === current.category)
    .slice(0, limit)
    .concat(
      PRODUCTS.filter((p) => p.slug !== slug && p.category !== current.category)
    )
    .slice(0, limit);
}
